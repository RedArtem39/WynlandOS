#!/usr/bin/env python3
"""WynlandOS - the kernel's symbol table, for loadable modules (kernel/module.c).

    tools/ksyms.py [kernel.elf]        C source of ksyms_table/ksyms_count on stdout
                                       (no file: an empty table, for the first link)
    tools/ksyms.py --check a.elf b.elf every symbol at the same address in both

The kernel is linked three times (Makefile): with an empty table, then with
the table of that link -- which moves what follows it -- then with the table
of the second, which has the same names and so the same size: nothing moves
any more, and --check proves it.
"""
import subprocess
import sys


def symbols(elf):
    out = subprocess.run(['nm', '--defined-only', elf], capture_output=True, text=True, check=True).stdout
    syms = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 3:
            continue
        addr, kind, name = parts
        if kind not in 'TDBRVW' or name.startswith('ksyms_'):
            continue                                  # globals only; not the table itself
        syms.append((int(addr, 16), name))
    return sorted(set(syms), key=lambda s: s[1])


def emit(syms):
    print('/* generated by tools/ksyms.py: the kernel\'s global symbols (kernel/module.c) */')
    print('typedef struct { unsigned long long addr; const char *name; } KSym;')
    if not syms:
        print('const KSym ksyms_table[1] = { { 0, "" } };')
        print('const unsigned int ksyms_count = 0;')
        return
    print('const KSym ksyms_table[] = {')
    for addr, name in syms:
        print('    { 0x%016xULL, "%s" },' % (addr, name))
    print('};')
    print('const unsigned int ksyms_count = %d;' % len(syms))


def all_addrs(elf):
    out = subprocess.run(['nm', '--defined-only', elf], capture_output=True, text=True, check=True).stdout
    return {p[2]: p[0] for p in (l.split() for l in out.splitlines()) if len(p) == 3}


if len(sys.argv) > 1 and sys.argv[1] == '--check':
    a, b = all_addrs(sys.argv[2]), all_addrs(sys.argv[3])
    moved = [n for n in a if n in b and a[n] != b[n]]
    if moved or set(a) != set(b):
        sys.exit('ksyms: the last two links differ (%d moved, e.g. %s)' % (len(moved), moved[:5]))
    sys.exit(0)
emit(symbols(sys.argv[1]) if len(sys.argv) > 1 else [])
