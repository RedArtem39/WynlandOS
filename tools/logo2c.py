#!/usr/bin/env python3
"""
WynlandOS - assets/logo/wynland-logo.json -> include/wynland/logo_data.h

The vector logo as integer tables for include/wynland/logo_draw.h, which
the loader and the kernel both draw with (no floating point in either):
points and sizes in 1/16 px of the 1114 px original, colour coefficients
times 16, and a sine table (a turn = 1024 steps, Q14).

Usage: python3 tools/logo2c.py assets/logo/wynland-logo.json include/wynland/logo_data.h
"""
import json
import math
import sys


def main() -> None:
    src, dst = sys.argv[1], sys.argv[2]
    d = json.load(open(src))
    q = lambda v: int(round(v * 16))
    pts, blades = [], []
    for b in d['blades']:
        first = len(pts) // 2
        for x, y in b['outline']:
            pts += [q(x), q(y)]
        n = len(b['outline'])
        cx = sum(p[0] for p in b['outline']) / n
        cy = sum(p[1] for p in b['outline']) / n
        c = b['colour']
        k = [[int(round(v * 16)) for v in c[ch]] for ch in ('r', 'g', 'b')]
        blades.append((first, n, q(math.hypot(cx, cy)), q(c['centre'][0]), q(c['centre'][1]), q(c['size']), k))
    seam_pts, seams = [], []
    for s in d['seams']:
        first = len(seam_pts) // 2
        for x, y in s:
            seam_pts += [q(x), q(y)]
        seams.append((first, len(s)))

    def rows(vals, per=12):
        return ',\n'.join('    ' + ', '.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))

    out = ['/* Generated by tools/logo2c.py from assets/logo/wynland-logo.json -- do not edit. */',
           '#pragma once', '#include <wynland/types.h>', '',
           f'#define LOGO_RADIUS16   {q(d["radius"])}      /* the original\'s half width, 1/16 px */',
           f'#define LOGO_NBLADES    {len(blades)}',
           f'#define LOGO_NSEAMS     {len(seams)}', '',
           'typedef struct {',
           '    uint16_t first, count;      /* its outline in logo_pts */',
           '    int16_t  r16;               /* how far its middle is from the centre */',
           '    int16_t  cx16, cy16, size16;   /* the colour polynomial\'s frame */',
           '    int16_t  k[3][10];          /* r, g, b coefficients x 16 */',
           '} LogoBlade;', '',
           'typedef struct { uint16_t first, count; } LogoSeam;', '',
           f'static const int16_t logo_pts[{len(pts)}] = {{', rows(pts), '};', '',
           f'static const int16_t logo_seam_pts[{len(seam_pts)}] = {{', rows(seam_pts), '};', '',
           'static const LogoBlade logo_blades[LOGO_NBLADES] = {']
    for first, n, r, bx, by, bs, k in blades:
        ks = ', '.join('{' + ', '.join(str(v) for v in ch) + '}' for ch in k)
        out.append(f'    {{ {first}, {n}, {r}, {bx}, {by}, {bs}, {{ {ks} }} }},')
    out += ['};', '', 'static const LogoSeam logo_seams[LOGO_NSEAMS] = {',
            '    ' + ', '.join(f'{{ {a}, {b} }}' for a, b in seams), '};', '',
            '/* sin(2 pi i / 1024), Q14 */',
            'static const int16_t logo_sin[1024] = {',
            rows([int(round(math.sin(2 * math.pi * i / 1024) * 16384)) for i in range(1024)], 16), '};', '']
    open(dst, 'w', newline='\n').write('\n'.join(out))


if __name__ == '__main__':
    main()
