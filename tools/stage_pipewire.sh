#!/bin/bash
# WynlandOS - stage PipeWire for the image.
#
# Ubuntu's prebuilt PipeWire, WirePlumber and pipewire-pulse (glibc, like
# Qt): their .debs and every dependency the host does not have installed
# are fetched with `apt-get download` into a cache and unpacked there.
# The sound goes PipeWire -> its ALSA node -> alsa-lib's OSS plugin
# (libasound2-plugins) -> /dev/dsp -> the HDA driver: no ALSA kernel
# interface needed. build/pw_manifest.txt lists the programs, the modules
# and plugins at Ubuntu's paths (where the libraries look for them), the
# configuration, and the ldd closure, minus what other manifests ship.
#
# usage: tools/stage_pipewire.sh       (from the repo root, inside WSL)
set -euo pipefail
cd "$(dirname "$0")/.."
REPO=$PWD
CACHE=${PW_CACHE:-$HOME/.cache/wynland-pipewire}
ROOT=$CACHE/root
LIB=$ROOT/usr/lib/x86_64-linux-gnu
OUT=$REPO/build
MAN=$OUT/pw_manifest.txt

TOP="pipewire pipewire-bin libpipewire-0.3-modules libspa-0.2-modules pipewire-pulse pipewire-alsa
 wireplumber libasound2-plugins libasound2-data pulseaudio-utils"

# 1. fetch + unpack: the packages and every dependency missing on the host
mkdir -p "$CACHE/debs" "$ROOT"
deps=$(apt-cache depends --recurse --no-recommends --no-suggests --no-conflicts \
           --no-breaks --no-replaces --no-enhances $TOP 2>/dev/null \
       | grep -v '^ ' | grep -v '^<' | sort -u)
NEW=0
for p in $deps; do
    if dpkg-query -W -f='${Status}' "$p" 2>/dev/null | grep -q 'install ok installed'; then
        case " $TOP " in *" $p "*) ;; *) continue ;; esac
    fi
    if ! ls "$CACHE/debs/${p}_"*.deb >/dev/null 2>&1; then
        (cd "$CACHE/debs" && apt-get download "$p" >/dev/null 2>&1) || echo "  PW         (no package $p)"
        NEW=1
    fi
done
if [ $NEW = 1 ] || [ ! -f "$CACHE/.unpacked" ]; then
    for d in "$CACHE"/debs/*.deb; do dpkg-deb -x "$d" "$ROOT"; done
    touch "$CACHE/.unpacked"
fi
echo "  PW         PipeWire $(ls "$CACHE"/debs/pipewire_*.deb | sed 's/.*_\([0-9.]*\)-.*/\1/') from $CACHE"

# 2. what ships. Not the plugins for what this system has no stack for:
#    Bluetooth, JACK, cameras, video, Vulkan, AVB, FFmpeg
SKIP_SPA="bluez5 jack libcamera v4l2 vulkan avb ffmpeg videoconvert videotestsrc"
SKIP_MOD="bluez|jack|roc|raop|zeroconf|avb|snapcast|x11|ffado|libcamera|rtp-sap|vban|echo-cancel|filter-chain-lv2|lv2"
BINS="pipewire pipewire-pulse wireplumber wpctl pw-cli pw-dump pw-cat pw-play pw-record pw-top pw-metadata pw-link pactl paplay"
SHIP=""
for b in $BINS; do
    f=$ROOT/usr/bin/$b
    if [ -e "$f" ]; then SHIP="$SHIP $f"; else echo "  PW         WARNING: no program $b"; fi
done
MODS=$(ls "$LIB"/pipewire-0.3/*.so | grep -Ev "$SKIP_MOD" || true)
SPA=""
for d in "$LIB"/spa-0.2/*/; do
    n=$(basename "$d"); case " $SKIP_SPA " in *" $n "*) continue ;; esac
    SPA="$SPA $(ls "$d"*.so)"
done
WP=$(ls "$LIB"/wireplumber-0.5/*.so)
# GStreamer's PulseAudio sink: with the session's sound up, GStreamer
# (the browser, players) plays through pipewire-pulse, mixed with the rest,
# not beside PipeWire on /dev/dsp; without it, autoaudiosink falls back to
# osssink
#  (in gstreamer1.0-plugins-good -- tools/stage_gst.sh fetches it, ships only osssink)
GSTP="${GST_CACHE:-$HOME/.cache/wynland-gst}/root/usr/lib/x86_64-linux-gnu/gstreamer-1.0/libgstpulseaudio.so"
[ -f "$GSTP" ] || { echo "  PW         WARNING: no $GSTP (run tools/stage_gst.sh first)"; GSTP=""; }
ALSA="$LIB/alsa-lib/libasound_module_pcm_oss.so $LIB/alsa-lib/libasound_module_pcm_pipewire.so $LIB/alsa-lib/libasound_module_ctl_pipewire.so"

{
    echo "# generated by tools/stage_pipewire.sh -- do not edit"
    for d in pipewire-0.3 spa-0.2 wireplumber-0.5 alsa-lib; do echo "D /usr/lib/x86_64-linux-gnu/$d"; done
    for d in "$LIB"/spa-0.2/*/; do n=$(basename "$d"); case " $SKIP_SPA " in *" $n "*) continue ;; esac; echo "D /usr/lib/x86_64-linux-gnu/spa-0.2/$n"; done
    for b in $SHIP; do
        # pw-play and friends are links to pw-cat: copies of it (it looks at its own name)
        echo "F /usr/bin/$(basename "$b") $(readlink -f "$b")"
    done
    for f in $MODS $SPA $WP $ALSA; do
        [ -f "$f" ] && echo "F ${f#$ROOT} $f"
    done
    [ -z "$GSTP" ] || echo "F /lib64/gstreamer-1.0/libgstpulseaudio.so $GSTP"   # (where gst_manifest puts the plugins)
    # their data: PipeWire's and WirePlumber's own configuration and
    # scripts, alsa-lib's configuration tree
    for tree in usr/share/pipewire usr/share/wireplumber usr/share/alsa usr/share/alsa-card-profile; do
        [ -d "$ROOT/$tree" ] || continue
        (cd "$ROOT" && find "$tree" -type d | sort) | while read d; do echo "D /$d"; done
        (cd "$ROOT" && find "$tree" \( -type f -o -type l \) | sort) | while read f; do echo "F /$f $(readlink -f "$ROOT/$f")"; done
    done
    # this system's: the HDA output for PipeWire, no device monitors
    echo "D /etc/pipewire"; echo "D /etc/pipewire/pipewire.conf.d"
    echo "F /etc/pipewire/pipewire.conf.d/10-wynland.conf $REPO/rootfs/etc/pipewire/pipewire.conf.d/10-wynland.conf"
    echo "D /etc/wireplumber"; echo "D /etc/wireplumber/wireplumber.conf.d"
    echo "F /etc/wireplumber/wireplumber.conf.d/10-wynland.conf $REPO/rootfs/etc/wireplumber/wireplumber.conf.d/10-wynland.conf"
    echo "F /etc/asound.conf $REPO/rootfs/etc/asound.conf"
    echo "F /usr/lib/wynland/session-audio $REPO/rootfs/usr/lib/wynland/session-audio"
    # the autotest check (rootfs/etc/wynrc/services/pwtest, AUTOTEST=1)
    echo "F /usr/lib/wynland/pwtest $REPO/tests/pwtest.sh"
    echo "F /usr/lib/wynland/pitest $OUT/pitest.elf"
    echo "F /etc/wynrc/services/pwtest $REPO/rootfs/etc/wynrc/services/pwtest"
} > "$MAN"

# 3. libraries: the ldd closure, by soname into /lib64, minus what the
#    other manifests already ship
OTHER=""
[ -f "$REPO/ext2_manifest.txt" ] && OTHER="$REPO/ext2_manifest.txt"
for m in qt6_manifest.txt gst_manifest.txt wpe_manifest.txt base_manifest.txt quickshell_manifest.txt caelestia_manifest.txt; do [ -f "$OUT/$m" ] && OTHER="$OTHER $OUT/$m"; done
lddenv() { env LD_LIBRARY_PATH="$LIB:$LIB/pulseaudio:$LIB/pipewire-0.3" "$@"; }
for f in $SHIP $MODS $SPA $WP $ALSA $GSTP; do
    if [ -f "$f" ]; then lddenv ldd "$f" 2>/dev/null | awk '/=>/ && $3 ~ /^\// {print $1, $3}'; fi   # (not "&&": a missing last file failed the pipe)
done | sort -u | while read soname path; do
    if [ -n "$OTHER" ] && awk -v want="/lib64/$soname" '($1=="F"||$1=="Fo") && $2==want {found=1} END {exit !found}' $OTHER; then continue; fi
    echo "F /lib64/$soname $(readlink -f "$path")"
done | sort -u >> "$MAN"

missing=$(for f in $SHIP $MODS $SPA $WP $ALSA $GSTP; do [ -f "$f" ] && lddenv ldd "$f" 2>/dev/null | grep 'not found' | sed "s|^|$(basename "$f"): |" || true; done | sort -u)
if [ -n "$missing" ]; then echo "  PW         WARNING: unresolved:"; echo "$missing"; fi
echo "  PW         $(grep -c '^F' "$MAN") files in $MAN"
