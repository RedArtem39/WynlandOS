#!/bin/bash
# WynlandOS - stage the Wi-Fi firmware for the image: Intel's iwlwifi
# firmware for the AX201 (Qu / QuZ with the HR or JF radio, API 77 -- the
# version OpenBSD's iwx(4), which drivers/net/iwx.c ports, speaks), from
# Ubuntu's linux-firmware-intel-wireless package (zstd-compressed there,
# plain here), with its copyright file. drivers/net/iwx.c picks the file
# from the card's revision registers.
#
# usage: tools/stage_wifi.sh            (from the repo root, inside WSL)
set -euo pipefail
cd "$(dirname "$0")/.."
REPO=$PWD
CACHE=${WIFI_CACHE:-$HOME/.cache/wynland-fw}
ROOT=$CACHE/root
OUT=$REPO/build
MAN=$OUT/wifi_manifest.txt
FW=$CACHE/plain

PKG=linux-firmware-intel-wireless
NAMES="iwlwifi-QuZ-a0-hr-b0-77 iwlwifi-Qu-c0-hr-b0-77 iwlwifi-Qu-b0-hr-b0-77 iwlwifi-QuZ-a0-jf-b0-77"

mkdir -p "$CACHE/debs" "$ROOT" "$FW"
if ! ls "$CACHE/debs/${PKG}_"*.deb >/dev/null 2>&1; then
    (cd "$CACHE/debs" && apt-get download "$PKG" >/dev/null)
fi
if [ ! -f "$CACHE/.unpacked" ]; then
    dpkg-deb -x "$CACHE"/debs/${PKG}_*.deb "$ROOT"
    touch "$CACHE/.unpacked"
fi

SRC=$ROOT/lib/firmware
[ -d "$SRC" ] || SRC=$ROOT/usr/lib/firmware
{
    echo "# generated by tools/stage_wifi.sh -- do not edit"
    echo "D /lib/firmware"
    for n in $NAMES; do
        if [ ! -s "$FW/$n.ucode" ]; then
            if [ -f "$SRC/$n.ucode.zst" ]; then zstd -q -d -f "$SRC/$n.ucode.zst" -o "$FW/$n.ucode"
            elif [ -f "$SRC/$n.ucode" ]; then cp "$SRC/$n.ucode" "$FW/$n.ucode"
            else echo "  WIFI       no $n in $PKG" >&2; continue; fi
        fi
        echo "F /lib/firmware/$n.ucode $FW/$n.ucode"
    done
    echo "D /usr/share/doc"
    echo "D /usr/share/doc/$PKG"
    echo "F /usr/share/doc/$PKG/copyright $ROOT/usr/share/doc/$PKG/copyright"
} > "$MAN"
echo "  WIFI       $(grep -c '^F /lib/firmware' "$MAN") firmware files from $(ls "$CACHE"/debs/${PKG}_*.deb | sed 's/.*_\(20[0-9]*\).*/\1/')"
