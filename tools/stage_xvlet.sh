#!/bin/bash
# WynlandOS - stage the xvlet shell for the image.
#
# xvlet is its own project (github.com/RedArtem39/xvlet-shell): a
# Quickshell configuration, QML and its fonts. This lists its working copy
# (XVLET_DIR, default: ../xvlet-shell beside this repository) into
# build/xvlet_manifest.txt at /usr/share/xvlet, where Zerp starts it from
# (quickshell -p /usr/share/xvlet) for an account whose desktop is "xvlet".
#
# usage: tools/stage_xvlet.sh       (from the repo root)
set -euo pipefail
cd "$(dirname "$0")/.."
REPO=$PWD
SRC=$(cd "${XVLET_DIR:-$REPO/../xvlet-shell}" && pwd)
MAN=$REPO/build/xvlet_manifest.txt
mkdir -p "$REPO/build"
[ -f "$SRC/shell.qml" ] || { echo "  XVLET      no shell.qml in $SRC (XVLET_DIR)"; exit 1; }
{
    echo "# generated by tools/stage_xvlet.sh -- do not edit"
    echo "D /usr/share/xvlet"
    (cd "$SRC" && find . -path ./.git -prune -o -type d -print | sed 's|^\./||' | grep -v '^\.$' | sort) | while read -r d; do echo "D /usr/share/xvlet/$d"; done
    (cd "$SRC" && find . -path ./.git -prune -o -type f -print | sed 's|^\./||' | sort) | while read -r f; do echo "F /usr/share/xvlet/$f $SRC/$f"; done
    # its skin for wynlogin (the login screen), where wynlogin looks for
    # skins: "theme = xvlet" in /etc/wynland/login.conf picks it
    if [ -f "$SRC/wynlogin/Greeter.qml" ]; then
        echo "D /usr/share/wynlogin"
        echo "D /usr/share/wynlogin/themes"
        echo "D /usr/share/wynlogin/themes/xvlet"
        echo "F /usr/share/wynlogin/themes/xvlet/Greeter.qml $SRC/wynlogin/Greeter.qml"
    fi
} > "$MAN"
echo "  XVLET      $(grep -c '^F' "$MAN") files from $SRC ($(cd "$SRC" && git rev-parse --short HEAD 2>/dev/null || echo 'no commit'))"
